export function buildCoreCatalog(locale: Locale) {
  const index = order.indexOf(locale),
    result: Record<string, string> = {};
  if (index < 0) return result;
  for (const [ru, en, ...values] of rows) {
    result[ru] = values[index];
    result[en] = values[index];
  }
  return result;
}
