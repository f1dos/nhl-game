import { writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";

const TEAM_IDS = {
  "anaheim-ducks": "ANA",
  "boston-bruins": "BOS",
  "buffalo-sabres": "BUF",
  "calgary-flames": "CGY",
  "carolina-hurricanes": "CAR",
  "chicago-blackhawks": "CHI",
  "colorado-avalanche": "COL",
  "columbus-blue-jackets": "CBJ",
  "dallas-stars": "DAL",
  "detroit-red-wings": "DET",
  "edmonton-oilers": "EDM",
  "florida-panthers": "FLA",
  "los-angeles-kings": "LAK",
  "minnesota-wild": "MIN",
  "montreal-canadiens": "MTL",
  "nashville-predators": "NSH",
  "new-jersey-devils": "NJD",
  "new-york-islanders": "NYI",
  "new-york-rangers": "NYR",
  "ottawa-senators": "OTT",
  "philadelphia-flyers": "PHI",
  "pittsburgh-penguins": "PIT",
  "san-jose-sharks": "SJS",
  "seattle-kraken": "SEA",
  "st-louis-blues": "STL",
  "tampa-bay-lightning": "TBL",
  "toronto-maple-leafs": "TOR",
  "utah-mammoth": "UTA",
  "vancouver-canucks": "VAN",
  "vegas-golden-knights": "VGK",
  "washington-capitals": "WSH",
  "winnipeg-jets": "WPG",
};
const source = "https://puckpedia.com/injuries";
const html = execFileSync(
  "curl",
  [
    "-L",
    "--fail",
    "--silent",
    "--show-error",
    "-A",
    "Mozilla/5.0 NHL Manager data sync",
    source,
  ],
  { encoding: "utf8", maxBuffer: 20_000_000 },
);
const panel = html.slice(html.indexOf('data-panel="Team"'));
const rows = [...panel.matchAll(/<tr>([\s\S]*?)<\/tr>/g)].map((m) => m[1]);
let team = "";
const injuries = [];
const clean = (value) =>
  value
    .replace(/<[^>]+>/g, " ")
    .replace(/&[^;]+;/g, " ")
    .replace(/\s+/g, " ")
    .trim();
for (const row of rows) {
  const group = row.match(/href=['"]\/team\/([^'"]+)/);
  if (row.includes("pp_tbodygroup") && group) {
    team = TEAM_IDS[group[1]] ?? "";
    continue;
  }
  if (!team) continue;
  const player = row.match(
    /class=['"]pp_link['"] href=['"]\/player\/[^'"]+['"]>([^<]+)<\/a>/,
  );
  const cells = [
    ...row.matchAll(/<td(?: class="[^"]*")?>([\s\S]*?)<\/td>/g),
  ].map((m) => clean(m[1]));
  const returnDate = row.match(/Estimated Return:\s*([^<]+)/)?.[1]?.trim();
  const report = row.match(
    /<p class=['"]mt-2 mb-2 min-w-\[200px\]['"]>([\s\S]*?)<\/p>/,
  )?.[1];
  if (!player || cells.length < 4 || !returnDate) continue;
  const parsedReturn = new Date(`${returnDate} 12:00:00 UTC`);
  if (Number.isNaN(parsedReturn.valueOf())) continue;
  injuries.push({
    team,
    player: clean(player[1]),
    timeline: cells[1],
    status: cells[2],
    reason: cells[3],
    returnDate: parsedReturn.toISOString().slice(0, 10),
    report: clean(report ?? ""),
  });
}
if (injuries.length < 50)
  throw Error(`Injury coverage too low: ${injuries.length}`);
const fetchedAt = new Date().toISOString();
const out = `// Generated by scripts/sync-injuries.mjs. Do not edit.\nexport const NHL_INJURY_META = ${JSON.stringify({ source, fetchedAt, season: "2026/27" }, null, 2)} as const;\n\nexport interface NhlInjurySnapshot { team:string; player:string; timeline:string; status:string; reason:string; returnDate:string; report:string; }\n\nexport const NHL_INJURIES: NhlInjurySnapshot[] = ${JSON.stringify(injuries, null, 2)};\n`;
await writeFile(
  new URL("../src/data/nhl-injuries-2026-27.ts", import.meta.url),
  out,
);
console.log(`Wrote ${injuries.length} injuries`);
