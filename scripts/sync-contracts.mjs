const normalize = (value) =>
  value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
const money = (value) => Number(value.replace(/[$,]/g, ""));
const contracts = {};

for (const [team, slug] of Object.entries(teams)) {
  const url = `https://puckpedia.com/team/${slug}`;
  const html = execFileSync(
    "curl",
    ["-fsSL", "--max-time", "45", "--retry", "2", url],
    { encoding: "utf8", maxBuffer: 30 * 1024 * 1024 },
  );
  const rows = html.matchAll(/<tr class="group[^\"]*"[^>]*>([\s\S]*?)<\/tr>/g);
  for (const [, row] of rows) {
    const player = row.match(
      /href="\/player\/([^\"]+)"[^>]*translate="no">([^<]+)<\/a>/,
    );
    const aavs = [...row.matchAll(/data-aav="(\$[\d,]+)"/g)]
      .map((match) => money(match[1]))
      .filter((value) => value > 0);
    if (!player || !aavs.length) continue;
    const display = player[2].trim();
    const [last, first] = display.split(",").map((part) => part.trim());
    if (!first || !last) continue;
    const expiryStatus =
      row.match(/pp-(ufa|rfa)/i)?.[1]?.toUpperCase() ?? "UFA";
    const explicitExpiryYear = row.match(
      /class="[^"]*text-right[^"]*"[^>]*>(\d{4})<\/div>/i,
    )?.[1];
    const visibleYears = aavs.length;
    const expiryYear = explicitExpiryYear
      ? Number(explicitExpiryYear)
      : 2026 + visibleYears;
    const remainingYears = Math.max(1, expiryYear - 2026);
    const aav = aavs[0];
    const key = `${team}|${normalize(`${first} ${last}`)}`;
    const candidate = {
      team,
      player: `${first} ${last}`,
      playerSlug: player[1],
      aav,
      remainingYears,
      remainingValue: aav * remainingYears,
      expiryYear,
      expiryStatus,
      sourceUrl: `https://puckpedia.com/player/${player[1]}`,
    };
    if (!contracts[key] || candidate.expiryYear > contracts[key].expiryYear)
      contracts[key] = candidate;
  }
  console.log(
    `${team}: ${Object.keys(contracts).filter((key) => key.startsWith(`${team}|`)).length}`,
  );
}

if (Object.keys(contracts).length < 600)
  throw new Error(
    `Contract coverage too low: ${Object.keys(contracts).length}`,
  );
const payload = `// Generated by scripts/sync-contracts.mjs. Do not edit manually.
// Source: public PuckPedia team contract tables, 2026/27 snapshot.
export const NHL_CONTRACT_META = ${JSON.stringify(
  {
    season: "2026/27",
    fetchedAt: new Date().toISOString(),
    source: "https://puckpedia.com/teams",
    valueMeaning:
      "AAV and remaining contract commitment from the 2026/27 season onward",
  },
  null,
  2,
)} as const;

export interface NhlContractSnapshot {
  team: string;
  player: string;
  playerSlug: string;
  aav: number;
  remainingYears: number;
  remainingValue: number;
  expiryYear: number;
  expiryStatus: "UFA" | "RFA";
  sourceUrl: string;
}

export const NHL_CONTRACTS_BY_NAME: Record<string, NhlContractSnapshot> = ${JSON.stringify(contracts, null, 2)};
`;
const output = path.resolve("src/data/nhl-contracts-2026-27.ts");
await fs.writeFile(output, payload);
console.log(`Wrote ${output}: ${Object.keys(contracts).length} contracts.`);
