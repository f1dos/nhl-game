const endpoint = "https://lscluster.hockeytech.com/feed/index.php";
const decode = async (url) => {
  const text = execFileSync(
    "curl",
    ["--fail", "--silent", "--show-error", url],
    { encoding: "utf8", maxBuffer: 20_000_000 },
  );
  return JSON.parse(text.replace(/^\(/, "").replace(/\)\s*$/, ""));
};
const position = (p = "C") =>
  p === "G"
    ? "G"
    : p.includes("D")
      ? "D"
      : ["LW", "RW", "C"].includes(p)
        ? p
        : "C";
const nation = (place = "") =>
  /, (AB|BC|MB|NB|NL|NS|NT|NU|ON|PE|QC|SK|YT)$/.test(place)
    ? "CAN"
    : /, [A-Z]{2}$/.test(place)
      ? "USA"
      : place.split(", ").at(-1)?.slice(0, 3).toUpperCase() || "INT";
const output = {};
for (const [leagueName, cfg] of Object.entries(leagues)) {
  const qs = new URLSearchParams({
    feed: "statviewfeed",
    view: "teamsForSeason",
    season: String(cfg.season),
    key: cfg.key,
    client_code: cfg.client,
  });
  const teams = (await decode(`${endpoint}?${qs}`)).teams.filter(
    (t) => Number(t.id) > 0,
  );
  output[leagueName] = [];
  for (const team of teams) {
    const rosterQs = new URLSearchParams({
      feed: "statviewfeed",
      view: "roster",
      team_id: String(team.id),
      season_id: String(cfg.season),
      key: cfg.key,
      client_code: cfg.client,
      site_id: String(cfg.site),
      league_id: String(cfg.league),
      lang: "en",
    });
    const roster = await decode(`${endpoint}?${rosterQs}`);
    for (const section of roster.roster?.[0]?.sections ?? [])
      for (const item of section.data ?? []) {
        const p = item.row;
        if (!p?.player_id || !p?.name) continue;
        output[leagueName].push({
          id: `${cfg.client}-${p.player_id}`,
          name: p.name,
          pos: position(p.position),
          number: Number(p.tp_jersey_number) || 0,
          birthDate: p.birthdate,
          birthplace: p.birthplace,
          nation: nation(p.birthplace),
          club: team.name,
          clubLogo: team.logo,
          affiliate:
            leagueName === "AHL" ? (affiliates[team.name] ?? null) : null,
        });
      }
  }
}
